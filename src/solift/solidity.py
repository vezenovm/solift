"""The Solidity back end: a model as a pure function, with its inputs as parameters.

The file holds a library with a struct of the inputs, so that no model runs out of stack slots, the modeled function
and its callees, and a host contract with one external function that a Halmos test can call. The operators are the
Solidity operators and OpenZeppelin Math calls of the table in ops.py, in the order of the source, so the solver's work
to prove this code equal to the contract stays small. Named constants keep their declared types.
"""

from __future__ import annotations

import re

from solift.ir import (
    Assign,
    Call,
    Const,
    Expr,
    Function,
    If,
    Let,
    Model,
    Op,
    Return,
    Revert,
    Stmt,
    Tuple,
    Unpack,
    Var,
    parts,
    walk,
)
from solift.ops import TABLE

# The first solc that has abi.encodeCall.
ENCODE_CALL = (0, 8, 11)

_ENCODE_CALL = re.compile(r"abi\.encodeCall\((\w+(?:\.\w+)*), \(([^()]*)\)\)")


def version(solc: str) -> tuple[int, ...]:
    """A solc version such as `0.8.10` or `0.8.10+commit.fc410830` as numbers, or () for an empty one."""
    match = re.match(r"(\d+)\.(\d+)\.(\d+)", solc)
    return tuple(int(n) for n in match.groups()) if match else ()


def encoded_call(function: str, arguments: str, solc: str) -> str:
    """The calldata of a call of `function` (`target.f`) with `arguments`, their texts separated by commas:
    `abi.encodeCall(target.f, (a, b))`, which checks the arguments against the function's parameters, or for solc
    below 0.8.11, which lacks it, `abi.encodeWithSelector(target.f.selector, a, b)`."""
    arguments = arguments.strip()
    if not solc or version(solc) >= ENCODE_CALL:
        return f"abi.encodeCall({function}, ({arguments}))"
    return f"abi.encodeWithSelector({function}.selector{', ' + arguments if arguments else ''})"


def encoded_calls(text: str, solc: str) -> str:
    """`text` with each `abi.encodeCall(f, (a, b))` whose arguments hold no parentheses written as encoded_call writes
    it for `solc`."""
    text = _ENCODE_CALL.sub(lambda m: encoded_call(m.group(1), m.group(2), solc), text)
    if "abi.encodeCall(" in text and solc and version(solc) < ENCODE_CALL:
        raise ValueError(f"an abi.encodeCall that solc {solc} lacks is left in the generated test")
    return text


def oldest(models) -> str:
    """The oldest solc that built one of the models, or empty if none is known."""
    known = [model.solc for model in models if model.solc]
    return min(known, key=version, default="")


def names(model: Model) -> tuple[str, str]:
    """The library and host contract names: `Quoter._quote` gives `QuoterQuoteModel` and `QuoterQuoteHost`, or the
    model's stem with the same suffixes."""
    stem = (
        model.stem or model.contract + model.function.name.lstrip("_")[:1].upper() + model.function.name.lstrip("_")[1:]
    )
    return stem + "Model", stem + "Host"


def imports(model: Model) -> tuple[str, ...]:
    """The import directives of the model's Solidity: of Math, then the others."""
    math = (f'import {{Math}} from "{model.math}";',) if model.math else ()
    return math + model.imports


def source(model: Model) -> str:
    library, host = names(model)
    lines = [
        f"// SPDX-License-Identifier: {model.spdx}",
        f"// Generated by solift from {model.name}. Do not edit.",
    ]
    if model.effects:
        compares = "the result, the outputs" if model.outputs else "the result"
        lines.append(f"// The model leaves out these writes and events. The link compares {compares} and the revert.")
        lines += [f"//   {effect}" for effect in model.effects]
    lines += [f"pragma solidity {model.pragma};", ""]
    if imports(model):
        lines += [*imports(model), ""]
    lines.append(f"library {library} {{")
    constants = _constants(model)
    for name, const in constants.items():
        lines.append(f"  {const.type.solidity} internal constant {name} = {_literal(const)};")
    if constants:
        lines.append("")
    lines.append("  struct Inputs {")
    lines += [f"    {v.type.solidity} {v.name};" for v in model.inputs]
    lines.append("  }")
    for function in (model.function, *model.callees):
        lines.append("")
        lines += _function(function, top=function is model.function)
    lines += [
        "}",
        "",
        f"contract {host} {{",
        f"  function run({library}.Inputs memory i) external pure returns ({model.function.returns.solidity}) {{",
        f"    return {library}.{model.function.name}(i);",
        "  }",
        "}",
        "",
    ]
    return "\n".join(lines)


def _constants(model: Model) -> dict[str, Const]:
    found: dict[str, Const] = {}
    for function in (model.function, *model.callees):
        for e in walk(function):
            if isinstance(e, Const) and e.name is not None:
                seen = found.setdefault(e.name, e)
                if seen.value != e.value or seen.type != e.type:
                    raise ValueError(f"two constants named {e.name}")
    return found


def _function(function: Function, top: bool) -> list[str]:
    params = ["Inputs memory i"] + ([] if top else [f"{p.type.solidity} {p.name}" for p in function.params])
    names = function.results or (None,) * len(parts(function.returns))
    pairs = zip(names, parts(function.returns), strict=True)
    returns = ", ".join(t.solidity + (f" {v.name}" if v else "") for v, t in pairs)
    lines = [f"  function {function.name}({', '.join(params)}) internal pure returns ({returns}) {{"]
    lines += _block(function.body, "    ")
    lines.append("  }")
    return lines


def _block(stmts: tuple[Stmt, ...], indent: str) -> list[str]:
    lines = []
    for stmt in stmts:
        if isinstance(stmt, Let):
            lines.append(f"{indent}{stmt.var.type.solidity} {stmt.var.name} = {expr(stmt.expr, top=True)};")
        elif isinstance(stmt, Assign):
            lines.append(f"{indent}{stmt.var.name} = {expr(stmt.expr, top=True)};")
        elif isinstance(stmt, Unpack):
            names = ["" if v is None else f"{v.type.solidity} {v.name}" if stmt.declare else v.name for v in stmt.vars]
            lines.append(f"{indent}({', '.join(names)}) = {expr(stmt.expr, top=True)};")
        elif isinstance(stmt, Return):
            lines.append(f"{indent}return {expr(stmt.expr, top=True)};")
        elif isinstance(stmt, Revert):
            lines.append(f"{indent}revert();")
        elif isinstance(stmt, If):
            lines.append(f"{indent}if ({expr(stmt.cond, top=True)}) {{")
            lines += _block(stmt.then, indent + "  ")
            if stmt.orelse:
                lines.append(f"{indent}}} else {{")
                lines += _block(stmt.orelse, indent + "  ")
            lines.append(f"{indent}}}")
        else:
            raise TypeError(f"no statement {stmt!r}")
    return lines


def expr(e: Expr, top: bool = False) -> str:
    """The Solidity text of an expression. Each operator except a library call is in parentheses, unless it is the
    whole expression of a statement."""
    if isinstance(e, Var):
        return f"i.{e.name}" if e.input else e.name
    if isinstance(e, Const):
        return e.name if e.name is not None else _literal(e)
    if isinstance(e, Call):
        return f"{e.function}({', '.join(['i'] + [expr(arg) for arg in e.args])})"
    if isinstance(e, Tuple):
        return f"({', '.join(expr(arg, top=True) for arg in e.args)})"
    if isinstance(e, Op):
        operator = TABLE[e.op]
        # A conversion's one operand is inside its parentheses already.
        args = (expr(arg, top=operator.kind == "convert") for arg in e.args)
        text = operator.solidity.format(*args, type=e.type.solidity)
        return text if top or operator.kind in ("library", "convert") else f"({text})"
    raise TypeError(f"no expression {e!r}")


def _literal(const: Const) -> str:
    if isinstance(const.value, bool):
        return "true" if const.value else "false"
    return const.text if const.text is not None else str(const.value)
