"""The Solidity back end: a model as a pure function, with its inputs as parameters.

The file holds a library with a struct of the inputs, so that no model runs out of stack slots, the modeled function
and its callees, and a host contract with one external function that a Halmos test can call. The operators are the
Solidity operators and OpenZeppelin Math calls of the table in ops.py, in the order of the source, so the solver's work
to prove this code equal to the contract stays small. Named constants keep their declared types.
"""

from __future__ import annotations

from z3sol.ir import Assign, Call, Const, Expr, Function, If, Let, Model, Op, Return, Stmt, Var, walk
from z3sol.ops import TABLE


def names(model: Model) -> tuple[str, str]:
    """The library and host contract names: `DepositSubsidy._quoteSubsidy` gives `DepositSubsidyQuoteSubsidyModel`
    and `DepositSubsidyQuoteSubsidyHost`, or the model's stem with the same suffixes."""
    stem = (
        model.stem or model.contract + model.function.name.lstrip("_")[:1].upper() + model.function.name.lstrip("_")[1:]
    )
    return stem + "Model", stem + "Host"


def source(model: Model) -> str:
    library, host = names(model)
    lines = [
        f"// SPDX-License-Identifier: {model.spdx}",
        f"// Generated by z3sol from {model.name}. Do not edit.",
        f"pragma solidity {model.pragma};",
        "",
    ]
    if model.imports:
        lines += [*model.imports, ""]
    lines.append(f"library {library} {{")
    constants = _constants(model)
    for name, const in constants.items():
        lines.append(f"  {const.type.solidity} internal constant {name} = {_literal(const)};")
    if constants:
        lines.append("")
    lines.append("  struct Inputs {")
    lines += [f"    {v.type.solidity} {v.name};" for v in model.inputs]
    lines.append("  }")
    for function in (model.function, *model.callees):
        lines.append("")
        lines += _function(function, top=function is model.function)
    lines += [
        "}",
        "",
        f"contract {host} {{",
        f"  function run({library}.Inputs memory i) external pure returns ({model.function.returns.solidity}) {{",
        f"    return {library}.{model.function.name}(i);",
        "  }",
        "}",
        "",
    ]
    return "\n".join(lines)


def _constants(model: Model) -> dict[str, Const]:
    found: dict[str, Const] = {}
    for function in (model.function, *model.callees):
        for e in walk(function):
            if isinstance(e, Const) and e.name is not None:
                seen = found.setdefault(e.name, e)
                if seen.value != e.value or seen.type != e.type:
                    raise ValueError(f"two constants named {e.name}")
    return found


def _function(function: Function, top: bool) -> list[str]:
    params = ["Inputs memory i"] + ([] if top else [f"{p.type.solidity} {p.name}" for p in function.params])
    returns = function.returns.solidity + (f" {function.result.name}" if function.result is not None else "")
    lines = [f"  function {function.name}({', '.join(params)}) internal pure returns ({returns}) {{"]
    lines += _block(function.body, "    ")
    lines.append("  }")
    return lines


def _block(stmts: tuple[Stmt, ...], indent: str) -> list[str]:
    lines = []
    for stmt in stmts:
        if isinstance(stmt, Let):
            lines.append(f"{indent}{stmt.var.type.solidity} {stmt.var.name} = {expr(stmt.expr, top=True)};")
        elif isinstance(stmt, Assign):
            lines.append(f"{indent}{stmt.var.name} = {expr(stmt.expr, top=True)};")
        elif isinstance(stmt, Return):
            lines.append(f"{indent}return {expr(stmt.expr, top=True)};")
        elif isinstance(stmt, If):
            lines.append(f"{indent}if ({expr(stmt.cond, top=True)}) {{")
            lines += _block(stmt.then, indent + "  ")
            if stmt.orelse:
                lines.append(f"{indent}}} else {{")
                lines += _block(stmt.orelse, indent + "  ")
            lines.append(f"{indent}}}")
        else:
            raise TypeError(f"no statement {stmt!r}")
    return lines


def expr(e: Expr, top: bool = False) -> str:
    """The Solidity text of an expression. Each operator except a library call is in parentheses, unless it is the
    whole expression of a statement."""
    if isinstance(e, Var):
        return f"i.{e.name}" if e.input else e.name
    if isinstance(e, Const):
        return e.name if e.name is not None else _literal(e)
    if isinstance(e, Call):
        return f"{e.function}({', '.join(['i'] + [expr(arg) for arg in e.args])})"
    if isinstance(e, Op):
        operator = TABLE[e.op]
        text = operator.solidity.format(*(expr(arg) for arg in e.args))
        return text if top or operator.kind == "library" else f"({text})"
    raise TypeError(f"no expression {e!r}")


def _literal(const: Const) -> str:
    if isinstance(const.value, bool):
        return "true" if const.value else "false"
    return const.text if const.text is not None else str(const.value)
