import dataclasses

import pytest

from tests.models import quote
from z3sol.link import Check, Link, LinkError, generate

DEPOSIT_LINK = Link(
    setup="proofs/subsidies/test/SubsidySetup.sol:DepositSubsidySetup",
    call="subsidy.exposedQuote(_fee, _reimbursableGas, _tokenPerEth)",
    adapters={
        ("targetRelayerProfit", "maxSubsidyPerOperation"): "_configure(targetRelayerProfit, maxSubsidyPerOperation);",
        "pot": "token.set(address(subsidy), pot, 1);",
        "baseFee": "vm.fee(baseFee);",
    },
    observed={"txGasPrice": "tx.gasprice"},
)

LINK_TEST = """\
// SPDX-License-Identifier: Apache-2.0
// Generated by z3sol: the link of DepositSubsidy._quoteSubsidy to its model. Do not edit.
pragma solidity >=0.8.27;

import {DepositSubsidySetup} from "proofs/subsidies/test/SubsidySetup.sol";
import {DepositSubsidyQuoteSubsidyModel, DepositSubsidyQuoteSubsidyHost} from "./DepositSubsidyQuoteSubsidy.sol";

contract DepositSubsidyQuoteSubsidyLink is DepositSubsidySetup {
  function check_link(
    uint256 _fee,
    uint256 _reimbursableGas,
    uint256 _tokenPerEth,
    uint128 targetRelayerProfit,
    uint128 maxSubsidyPerOperation,
    uint256 pot,
    uint256 baseFee
  ) public {
    _configure(targetRelayerProfit, maxSubsidyPerOperation);
    token.set(address(subsidy), pot, 1);
    vm.fee(baseFee);
    (bool codeOk, bytes memory codeOut) = address(subsidy).call(
      abi.encodeCall(subsidy.exposedQuote, (_fee, _reimbursableGas, _tokenPerEth))
    );
    DepositSubsidyQuoteSubsidyHost host = new DepositSubsidyQuoteSubsidyHost();
    DepositSubsidyQuoteSubsidyModel.Inputs memory i = DepositSubsidyQuoteSubsidyModel.Inputs({
      _fee: _fee,
      _reimbursableGas: _reimbursableGas,
      _tokenPerEth: _tokenPerEth,
      targetRelayerProfit: targetRelayerProfit,
      maxSubsidyPerOperation: maxSubsidyPerOperation,
      pot: pot,
      txGasPrice: tx.gasprice,
      baseFee: baseFee
    });
    (bool modelOk, bytes memory modelOut) = address(host).call(abi.encodeCall(host.run, (i)));
    assert(codeOk == modelOk);
    if (codeOk) {
      assert(abi.decode(codeOut, (uint256)) == abi.decode(modelOut, (uint256)));
    }
  }
}
"""


def test_the_link_test_sets_each_input_through_the_call_an_adapter_or_an_observed_value():
    generated = generate(quote(), DEPOSIT_LINK)
    assert generated.files["DepositSubsidyQuoteSubsidyLink.t.sol"] == LINK_TEST


def test_the_run_declares_the_link_and_each_row_and_lemma_that_the_model_uses():
    generated = generate(quote(), DEPOSIT_LINK)
    assert set(generated.files) == {
        "DepositSubsidyQuoteSubsidy.sol",
        "DepositSubsidyQuoteSubsidyLink.t.sol",
        "DepositSubsidyQuoteSubsidyOperators.t.sol",
    }
    rows = {c.function for c in generated.checks if c.contract == "DepositSubsidyQuoteSubsidyOperators"}
    assert rows == {
        "check_row_addRevertsExactlyOnOverflow",
        "check_lemma_minIsTheSmallerValue",
        "check_row_mulRevertsExactlyOnOverflow",
        "check_row_mulDivOfHalfWidthOperandsRevertsExactlyOnZero",
        "check_lemma_mulModOfHalfWidthOperandsIsTheProduct",
        "check_lemma_mulDivOfHalfWidthOperandsIsTheFloor",
        "check_row_subRevertsExactlyBelowZero",
    }
    assert Check("DepositSubsidyQuoteSubsidyLink", "check_link") in generated.checks
    operators = generated.files["DepositSubsidyQuoteSubsidyOperators.t.sol"]
    assert 'import {Math} from "@oz/utils/math/Math.sol";' in operators
    assert "function check_row_divRevertsExactlyOnZero" not in operators


@pytest.mark.parametrize(
    "change, message",
    [
        ({"adapters": {**DEPOSIT_LINK.adapters, "pot": "token.set(address(subsidy), 0, 1);"}}, "does not use it"),
        ({"observed": {}}, "no call argument, adapter or observed value sets the input txGasPrice"),
        ({"observed": {"txGasPrice": "tx.gasprice", "baseFee": "block.basefee"}}, "sets baseFee twice"),
        ({"observed": {"txGasPrice": "tx.gasprice", "gasPrice": "tx.gasprice"}}, "gasPrice, which is not an input"),
        (
            {
                "call": "subsidy.exposedQuote(_fee, _reimbursableGas, 1)",
                "observed": {"txGasPrice": "tx.gasprice", "_tokenPerEth": "1"},
            },
            "must reach the contract through the call",
        ),
        ({"call": "exposedQuote(_fee)"}, "is not target.function"),
    ],
)
def test_a_link_that_does_not_set_each_input_exactly_once_is_refused(change, message):
    link = dataclasses.replace(DEPOSIT_LINK, **change)
    with pytest.raises(LinkError, match=message):
        generate(quote(), link)
