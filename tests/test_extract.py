def quote_reference(_gas, _price, margin, cap, floor, pot, txGasPrice, baseFee):
    """Quoter._quote in plain Python integers. None means it reverts."""
    if _gas == 0:
        return 0
    if baseFee + TIP >= 2**256:
        return None
    gas_price = min(txGasPrice, baseFee + TIP)
    if _gas * gas_price >= 2**256:
        return None
    cost = _gas * gas_price * _price // WAD
    if cost >= 2**256:
        return None
    target = cost if margin == 0 else cost + margin
    if target >= 2**256:
        return None
    if target <= floor:
        return 0
    return min(min(target - floor, cap), pot)


QUOTE = """\
// SPDX-License-Identifier: Apache-2.0
// Generated by z3sol from Quoter._quote. Do not edit.
pragma solidity ^0.8.27;

import {Math} from "@openzeppelin/contracts/utils/math/Math.sol";

library QuoterQuoteModel {
  uint128 internal constant TIP = 2 gwei;
  uint256 internal constant WAD = 1e18;

  struct Inputs {
    uint256 _gas;
    uint256 _price;
    uint128 margin;
    uint128 cap;
    uint256 floor;
    uint256 pot;
    uint256 txGasPrice;
    uint256 baseFee;
  }

  function _quote(Inputs memory i) internal pure returns (uint256) {
    if (i._gas == 0) {
      return 0;
    }
    uint256 gasPrice = Math.min(i.txGasPrice, (i.baseFee + TIP));
    uint256 cost = Math.mulDiv((i._gas * gasPrice), i._price, WAD);
    uint256 target = _withMargin(i, cost, i.margin);
    if (target <= i.floor) {
      return 0;
    }
    return Math.min(Math.min((target - i.floor), i.cap), i.pot);
  }

  function _withMargin(Inputs memory i, uint256 _cost, uint256 _margin) internal pure returns (uint256) {
    if (_margin == 0) {
      return _cost;
    }
    return _cost + _margin;
  }
}

contract QuoterQuoteHost {
  function run(QuoterQuoteModel.Inputs memory i) external pure returns (uint256) {
    return QuoterQuoteModel._quote(i);
  }
}
"""


def test_the_quoter_model_is_the_function_with_its_reads_as_inputs(build):
    extraction = extract(build, f"{QUOTER}._quote", READS)
    model = extraction.model
    assert [(v.name, v.type) for v in model.inputs][2:4] == [("margin", uint(128)), ("cap", uint(128))]
    assert [r.source for r in model.reads] == list(READS)
    assert source(model) == QUOTE
    assert set(extraction.sources) == {
        "tests/fixtures/contracts/Quoter.sol",
        "lib/openzeppelin-contracts/contracts/utils/math/Math.sol",
    }


def test_the_quoter_terms_give_the_reference_result(build):
    model = extract(build, f"{QUOTER}._quote", READS).model
    rng = random.Random(1)
    edges = [0, 1, WAD, 2**128 - 1, 2**128, 2**256 - 1]
    outcomes = set()
    for _ in range(300):
        values = {}
        for v in model.inputs:
            values[v.name] = min(rng.choice(edges + [rng.getrandbits(rng.randint(1, 70))] * 4), v.type.bound - 1)
        expected = quote_reference(**values)
        reverts, value, _ = evaluate(model, values)
        assert reverts == (expected is None), values
        if not reverts:
            assert value == expected, values
        outcomes.add("reverts" if reverts else "pays" if value else "zero")
    assert outcomes == {"pays", "zero", "reverts"}


